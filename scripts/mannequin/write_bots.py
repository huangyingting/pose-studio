"""The mannequin's two bots written out (scripts/mannequin/bots.py makes them in Blender): their meshes'
bytes as one file in public/mannequin, named by its contents (bots.<sha1>.bin: a new one is never
taken for an old one kept by the browser), each starting on a 4-byte boundary; and lib/bots.ts with
the rest (their sizes, joints, where each one's bytes are in the file) and the file's name.
"""
import hashlib
import json
import os


def write(bots, targets, ts_path, bin_dir):
    """`bots`: {'male': {..., 'data': bytes}, 'female': {...}}. Returns the file's name."""
    blob = bytearray()
    meta = {}
    for k in ('male', 'female'):
        b = dict(bots[k])
        data = b.pop('data')
        b['offset'] = len(blob)
        b['bytes'] = len(data)
        blob += data
        while len(blob) % 4:
            blob += b'\0'
        meta[k] = b
    name = f'bots.{hashlib.sha1(blob).hexdigest()[:8]}.bin'
    os.makedirs(bin_dir, exist_ok=True)
    for old in os.listdir(bin_dir):
        if old.startswith('bots.') and old.endswith('.bin') and old != name:
            os.remove(os.path.join(bin_dir, old))
    with open(os.path.join(bin_dir, name), 'wb') as f:
        f.write(blob)
    with open(ts_path, 'w') as f:
        f.write('// Generated by scripts/mannequin/bots.py from Adobe Mixamo\'s Y Bot (a man) and X Bot (a woman). Do not edit.\n')
        f.write(f'export const BOT_TARGETS = {json.dumps(targets)} as const;\n\n')
        f.write(f'/** The bots\' meshes (public/mannequin), named by their contents; fetched once (lib/mannequin.ts loadBots). */\nexport const BOTS_FILE = {json.dumps(name)};\n\n')
        f.write('interface BotData {\n  height: number;\n  vertices: number;\n  triangles: number;\n  min: number[];\n  size: number[];\n  hipHalfWidth: number;\n  joints: Record<string, number[]>;\n  /** Where its bytes are in BOTS_FILE. */\n  offset: number;\n  bytes: number;\n}\n\n')
        f.write('export const BOTS: Record<\'male\' | \'female\', BotData> = ' + json.dumps(meta, indent=1) + ';\n')
    return name
